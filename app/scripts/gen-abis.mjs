// Generates src/server/chain/abis.generated.ts from Foundry artifacts + deployments.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../../contracts");
const out = (c, f = c) => JSON.parse(readFileSync(`${root}/out/${f}.sol/${c}.json`, "utf8")).abi;
const pick = (abi, names) => abi.filter((x) => names.includes(x.name) || x.type === "error");

const abis = {
  familiarRegistryAbi: out("FamiliarRegistry"),
  familiarFeederAbi: out("FamiliarFeeder"),
  familiarLogAbi: out("FamiliarLog"),
  permissionedResolverAbi: pick(out("PermissionedResolver"), [
    "setText", "text", "setAddr", "addr", "multicall", "hasRootRoles", "authorizeTextRoles",
  ]),
};
const deployments = {};
for (const id of ["11155111", "8453", "16661"]) {
  const p = `${root}/deployments/${id}.json`;
  if (existsSync(p)) deployments[id] = JSON.parse(readFileSync(p, "utf8"));
}
let src = "// AUTO-GENERATED by scripts/gen-abis.mjs from contracts/out. Do not edit.\n\n";
for (const [k, v] of Object.entries(abis)) src += `export const ${k} = ${JSON.stringify(v, null, 2)} as const;\n\n`;
src += `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`;
writeFileSync(resolve(import.meta.dirname, "../src/server/chain/abis.generated.ts"), src);
console.log("wrote abis.generated.ts", Object.keys(abis), Object.keys(deployments));
